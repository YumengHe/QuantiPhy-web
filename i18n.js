  // a run of text between two tags: the whole run, else its pieces between ' · ' separators, each without the
  // surrounding spaces and punctuation
  function text(s) {
    if (lang !== 'zh' || !hasWord(s)) return s;
    const whole = s.trim();
    if (ZH[whole] != null) return s.replace(whole, ZH[whole]);
    const parts = s.split(/( · )/);
    return parts.map((part) => {
      const m = part.match(/^([\s·:;,()\/→←=+|–—\-]*)(.*?)([\s·:;,()\/→←=+|–—\-]*)$/s);
      const core = m[2];
      if (!core || !hasWord(core)) return part;
      if (ZH[core] != null) return m[1] + ZH[core] + m[3];
      if (ZH[part.trim()] != null) return part.replace(part.trim(), ZH[part.trim()]);
      missing.add(parts.length > 1 ? part.trim() : whole);
      return part;
    }).join('');
  }
